    if rank == 16:
        _, pivcols = Big.T.rref()
        piv_rows = pivcols[:16]
        sub = sp.Matrix([rows[i] for i in piv_rows])
        det = sub.det()
        assert det != 0
        witness = (piv_rows, det)
        print(f"    explicit witness: the 16x16 submatrix from projector rows {piv_rows}")
        print(f"    has EXACT determinant {det} != 0  (rigorous, non-numerical certificate)")
    return dict(point=point_key, rank=rank, witness=witness, core_size=len(core))

