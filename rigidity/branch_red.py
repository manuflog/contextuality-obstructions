    print("=" * 96)
    core, pairs, bases, cert = load_concrete_core("p1")
    def qmul(u, v, B=0, C=-1):
        a, b = u; c, d = v
        return (a * c + C * b * d, a * d + b * c + B * b * d)
    def qconj(u, B=0):
        a, b = u; return (a + b * B, -b)
    def qadd(u, v): return (u[0] + v[0], u[1] + v[1])
    def dot_drop(x, y, drop):
        s = (0, 0)
        for c in range(4):
            if c == drop: continue
            s = qadd(s, qmul(qconj(x[c]), y[c]))
        return s
