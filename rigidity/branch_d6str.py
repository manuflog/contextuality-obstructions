def ring_dedupe(vectors, B, C):
    distinct, groups = [], []
    for idx, v in enumerate(vectors):
        placed = False
        for k, r in enumerate(distinct):
            if proportional(v, r, B, C):
                groups[k].append(idx); placed = True; break
        if not placed:
            distinct.append(v); groups.append([idx])
    return distinct, groups


def _sat_colorable(V, pairs, bases):
    from pysat.solvers import Cadical153
    solver = Cadical153()
    for i, j in pairs:
        solver.add_clause([-(i + 1), -(j + 1)])
    for b in bases:
        solver.add_clause([x + 1 for x in b])
    return solver.solve()


