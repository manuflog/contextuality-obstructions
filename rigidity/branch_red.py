    print(f"  [point {point_key}: {p['desc']}]")
    core, pairs, bases, cert = load_concrete_core(point_key)
    t0 = time.time()
    projs = []
    for ray in core:
        v = sp.Matrix([_to_gaussian(c) for c in ray])
        D = sum(a * a + b * b for a, b in ray)
        assert D != 0
        projs.append((v * v.H) / D)
    rows = [_flatten(P) for P in projs]
    Big = sp.Matrix(rows)
    rank = Big.rank()
    print(f"    89 projectors built; C-linear span of {{P_j}} in M_4(C) (16-complex-dim ambient): "
          f"rank = {rank}   ({time.time()-t0:.2f}s)")
