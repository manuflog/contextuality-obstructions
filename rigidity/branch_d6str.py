def _gaussian_int_projector_numerator(ray_ring):
    """P_num = v v^dagger (GAUSSIAN-INTEGER numerator, D=|v|^2 dropped -- rank/commutant of
       {P_j} is unaffected by rescaling each generator by its own positive real D_j, since
       T P_j - P_j T = 0  <=>  T P_num_j - P_num_j T = 0 for D_j > 0). Returns a D6xD6 list of
       (re,im) python-int pairs."""
    out = [[None] * D6 for _ in range(D6)]
    for i in range(D6):
        a, b = ray_ring[i]
        for j in range(D6):
            c, dd = ray_ring[j]
            cj = (c, -dd)  # conj(v_j)
            re = a * cj[0] - b * cj[1]
            im = a * cj[1] + b * cj[0]
            out[i][j] = (re, im)
    return out


def _kron_gauss_int(A, B):
    ra, ca = len(A), len(A[0]); rb, cb = len(B), len(B[0])
    out = [[None] * (ca * cb) for _ in range(ra * rb)]
    for i in range(ra):
        for j in range(ca):
            aij = A[i][j]
            for p in range(rb):
                for q in range(cb):
                    bpq = B[p][q]
                    re = aij[0] * bpq[0] - aij[1] * bpq[1]
                    im = aij[0] * bpq[1] + aij[1] * bpq[0]
                    out[i * rb + p][j * cb + q] = (re, im)
    return out


def _eye_gauss(n):
    return [[(1, 0) if i == j else (0, 0) for j in range(n)] for i in range(n)]


def _transpose(A):
    r, c = len(A), len(A[0])
    return [[A[i][j] for i in range(r)] for j in range(c)]


def _sub_gauss(A, B):
    return [[(a[0] - b[0], a[1] - b[1]) for a, b in zip(ra, rb)] for ra, rb in zip(A, B)]


