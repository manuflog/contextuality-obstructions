# ==================================================================================================
# STAGE 4 -- AUTOMORPHISM GROUP of the 46-ray/298-pair/17-basis core's orthogonality structure.
# WL color refinement (mirrors branch_m9str.wl_refine, dimension-general) FIRST; if it does not
# reach discreteness (it does NOT at d=6, unlike M9's one-round discreteness), a complete EXACT
# backtracking search within the WL-class restriction (necessary condition for any automorphism)
# determines the true |Aut| exactly, with pair-graph edge/non-edge consistency at every step and a
# full basis-preservation check on completion.
# ==================================================================================================
def wl_refine(V, pairs, bases, rounds=50):
    adj = [[] for _ in range(V)]
    for i, j in pairs: adj[i].append(j); adj[j].append(i)
    basis_of = [[] for _ in range(V)]
    for bi, b in enumerate(bases):
        for v in b: basis_of[v].append(bi)

    def relabel(sigs):
        uniq = sorted(set(sigs))
        m = {s: i for i, s in enumerate(uniq)}
        return [m[s] for s in sigs]

    color = relabel([(len(adj[v]), len(basis_of[v])) for v in range(V)])
    for _ in range(rounds):
        sig = []
        for v in range(V):
            nb = tuple(sorted(color[u] for u in adj[v]))
            bc = tuple(sorted(tuple(sorted(color[u] for u in bases[bi] if u != v)) for bi in basis_of[v]))
            sig.append((color[v], nb, bc))
        newcolor = relabel(sig)
        if newcolor == color: break
        color = newcolor
    return color


def exact_automorphism_group(V, pairs, bases):
    """Complete backtracking search for Aut(V,pairs,bases): candidate images for each vertex are
       restricted to its WL color class (necessary condition, never discards a true automorphism);
       assignment order processes the MOST constrained (smallest class) vertices first; pairwise
       edge/non-edge consistency is checked incrementally against every already-assigned vertex;
       full basis-set preservation is verified once an assignment is complete. Exhaustive over the
       (already-pruned) search space -- returns ALL automorphisms found."""
    adj = [set() for _ in range(V)]
    for i, j in pairs: adj[i].add(j); adj[j].add(i)
    basis_set = set(tuple(sorted(b)) for b in bases)
    color = wl_refine(V, pairs, bases)
    classes = defaultdict(list)
    for v, c in enumerate(color): classes[c].append(v)
    order = sorted(range(V), key=lambda v: (len(classes[color[v]]), v))

    autos = []

    def backtrack(assigned, used_images):
        if len(assigned) == V:
            sigma = [assigned[v] for v in range(V)]
            for b in bases:
                if tuple(sorted(sigma[x] for x in b)) not in basis_set:
                    return
            autos.append(tuple(sigma))
            return
        v = next(c for c in order if c not in assigned)
        for w in classes[color[v]]:
            if w in used_images: continue
            ok = True
            for u, wu in assigned.items():
                if (u in adj[v]) != (wu in adj[w]):
                    ok = False; break
            if not ok: continue
            assigned[v] = w; used_images.add(w)
            backtrack(assigned, used_images)
            del assigned[v]; used_images.discard(w)

    backtrack({}, set())
    return autos, color, classes


